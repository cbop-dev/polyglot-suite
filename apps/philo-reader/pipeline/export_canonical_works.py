"""Philo Pipeline - Export TypeScript Canonical Works Catalog."""

import json
import sqlite3
from pathlib import Path
from typing import Optional
from .config import CANONICAL_WORKS, GENERATED_TS_DIR, BUILD_DIR


def export_ts(output_path: Optional[Path] = None):
    """Exports canonical works catalog as TypeScript for the SvelteKit frontend."""
    out_file = output_path or (GENERATED_TS_DIR / "canonicalWorks.generated.ts")
    out_file.parent.mkdir(parents=True, exist_ok=True)

    db_file = BUILD_DIR / "philo.sqlite3"
    sections_by_work_book = {}
    if db_file.exists():
        conn = sqlite3.connect(db_file)
        cur = conn.cursor()
        cur.execute(
            """SELECT work_code, chapter, count(DISTINCT section)
               FROM text_units
               WHERE corpus_id = 'grc'
               GROUP BY work_code, chapter"""
        )
        for w_code, ch, count in cur.fetchall():
            sections_by_work_book.setdefault(w_code, {})[ch] = count
        conn.close()

    lines = [
        "// Auto-generated by pipeline/export_canonical_works.py. Do not edit directly.",
        "",
        "export type PhiloCategory = 'allegorical' | 'exposition' | 'historical' | 'philosophical';",
        "",
        "export interface CanonicalWork {",
        "  code: string;",
        "  tlgId: string;",
        "  orderIndex: number;",
        "  category: PhiloCategory;",
        "  abbrev: string;",
        "  titleEnglish: string;",
        "  titleGreek: string;",
        "  titleLatin: string;",
        "  totalBooks: number;",
        "  totalSections: number;",
        "  sectionsByBook?: Record<number, number>;",
        "}",
        "",
        "export const CANONICAL_WORKS: CanonicalWork[] = [",
    ]

    for w in CANONICAL_WORKS:
        sec_map = sections_by_work_book.get(w.code, {})
        lines.append("  {")
        lines.append(f'    code: "{w.code}",')
        lines.append(f'    tlgId: "{w.tlg_id}",')
        lines.append(f"    orderIndex: {w.order_index},")
        lines.append(f'    category: "{w.category}",')
        lines.append(f'    abbrev: "{w.abbrev}",')
        lines.append(f'    titleEnglish: "{w.title_english}",')
        lines.append(f'    titleGreek: "{w.title_greek}",')
        lines.append(f'    titleLatin: "{w.title_latin}",')
        lines.append(f"    totalBooks: {w.total_books},")
        lines.append(f"    totalSections: {w.total_sections},")
        if sec_map:
            lines.append(f"    sectionsByBook: {json.dumps(sec_map)},")
        lines.append("  },")

    lines.append("];")
    lines.append("")
    lines.append("export const WORKS_BY_CODE: Record<string, CanonicalWork> = Object.fromEntries(")
    lines.append("  CANONICAL_WORKS.map((w) => [w.code, w])")
    lines.append(");")
    lines.append("")
    lines.append("export const WORKS_BY_TLG: Record<string, CanonicalWork> = Object.fromEntries(")
    lines.append("  CANONICAL_WORKS.map((w) => [w.tlgId, w])")
    lines.append(");")
    lines.append("")

    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"✓ Exported canonical works TypeScript catalog to: {out_file}")


if __name__ == "__main__":
    export_ts()
