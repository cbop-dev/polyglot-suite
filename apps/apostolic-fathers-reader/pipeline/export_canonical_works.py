"""Apostolic Fathers Pipeline - Export TypeScript Canonical Works Catalog."""

import sqlite3
from pathlib import Path
from typing import Optional
from .config import CANONICAL_WORKS, GENERATED_TS_DIR, BUILD_DIR


def export_ts(output_path: Optional[Path] = None):
    out_file = output_path or (GENERATED_TS_DIR / "canonicalWorks.generated.ts")
    out_file.parent.mkdir(parents=True, exist_ok=True)

    db_file = BUILD_DIR / "apostolic-fathers.sqlite3"
    db_stats = {}
    if db_file.exists():
        conn = sqlite3.connect(db_file)
        cur = conn.cursor()
        cur.execute("SELECT work_code, min(chapter), max(chapter) FROM text_units GROUP BY work_code")
        for row in cur.fetchall():
            db_stats[row[0]] = (row[1], row[2])
        conn.close()

    lines = [
        "// Auto-generated by pipeline/export_canonical_works.py. Do not edit directly.",
        "",
        "export interface CanonicalWork {",
        "  code: string;",
        "  orderIndex: number;",
        "  category: 'epistle' | 'homily' | 'order' | 'treatise' | 'apocalypse' | 'martyrology' | 'apology';",
        "  titleEnglish: string;",
        "  titleGreek: string;",
        "  titleLatin?: string;",
        "  minChapter: number;",
        "  totalChapters: number;",
        "}",
        "",
        "export const CANONICAL_WORKS: CanonicalWork[] = [",
    ]

    for w in CANONICAL_WORKS:
        min_ch, max_ch = db_stats.get(w.code, (1, w.total_chapters))
        lines.append("  {")
        lines.append(f'    code: "{w.code}",')
        lines.append(f"    orderIndex: {w.order_index},")
        lines.append(f'    category: "{w.category}",')
        lines.append(f'    titleEnglish: "{w.title_english}",')
        lines.append(f'    titleGreek: "{w.title_greek}",')
        if w.title_latin:
            lines.append(f'    titleLatin: "{w.title_latin}",')
        lines.append(f"    minChapter: {min_ch},")
        lines.append(f"    totalChapters: {max_ch},")
        lines.append("  },")

    lines.append("];")
    lines.append("")
    lines.append("export const WORKS_BY_CODE: Record<string, CanonicalWork> = Object.fromEntries(")
    lines.append("  CANONICAL_WORKS.map((w) => [w.code, w])")
    lines.append(");")
    lines.append("")

    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"✓ Generated {out_file.name} with {len(CANONICAL_WORKS)} works.")


if __name__ == "__main__":
    export_ts()

