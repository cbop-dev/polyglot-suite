"""Josephus Pipeline - Export TypeScript Canonical Works Catalog."""

import json
import sqlite3
from pathlib import Path
from typing import Optional
from .config import CANONICAL_WORKS, GENERATED_TS_DIR, BUILD_DIR


def export_ts(output_path: Optional[Path] = None):
    """Exports canonical works catalog as TypeScript for the SvelteKit frontend."""
    out_file = output_path or (GENERATED_TS_DIR / "canonicalWorks.generated.ts")
    out_file.parent.mkdir(parents=True, exist_ok=True)

    db_file = BUILD_DIR / "josephus.sqlite3"
    sections_by_work_book = {}
    if db_file.exists():
        conn = sqlite3.connect(db_file)
        cur = conn.cursor()
        cur.execute(
            """SELECT work_code, book, count(DISTINCT section_num)
               FROM text_units
               WHERE corpus_id = 'josephus_grc'
               GROUP BY work_code, book"""
        )
        for w_code, b, count in cur.fetchall():
            sections_by_work_book.setdefault(w_code, {})[b] = count
        conn.close()

    lines = [
        "// Auto-generated by pipeline/export_canonical_works.py. Do not edit directly.",
        "",
        "export type JosephusCategory = 'history' | 'autobiography' | 'apology';",
        "",
        "export interface CanonicalWork {",
        "  code: string;",
        "  tlgId: string;",
        "  orderIndex: number;",
        "  category: JosephusCategory;",
        "  abbrev: string;",
        "  titleEnglish: string;",
        "  titleGreek: string;",
        "  titleLatin: string;",
        "  totalBooks: number;",
        "  defaultBook: number;",
        "  sectionsByBook?: Record<number, number>;",
        "}",
        "",
        "export const CANONICAL_WORKS: CanonicalWork[] = [",
    ]

    for w in CANONICAL_WORKS:
        sec_map = sections_by_work_book.get(w.code, {})
        lines.append("  {")
        lines.append(f'    code: "{w.code}",')
        lines.append(f'    tlgId: "{w.tlg_id}",')
        lines.append(f"    orderIndex: {w.order_index},")
        lines.append(f'    category: "{w.category}",')
        lines.append(f'    abbrev: "{w.abbrev}",')
        lines.append(f'    titleEnglish: "{w.title_english}",')
        lines.append(f'    titleGreek: "{w.title_greek}",')
        lines.append(f'    titleLatin: "{w.title_latin}",')
        lines.append(f"    totalBooks: {w.total_books},")
        lines.append(f"    defaultBook: {w.default_book},")
        if sec_map:
            lines.append(f"    sectionsByBook: {json.dumps(sec_map)},")
        lines.append("  },")

    lines.append("];")
    lines.append("")
    lines.append("export const WORK_BY_CODE = new Map(CANONICAL_WORKS.map((w) => [w.code, w]));")
    lines.append("")
    lines.append("export function getWork(code: string | null | undefined): CanonicalWork | undefined {")
    lines.append("  if (!code) return undefined;")
    lines.append("  const direct = WORK_BY_CODE.get(code);")
    lines.append("  if (direct) return direct;")
    lines.append("  const lower = code.toLowerCase();")
    lines.append("  return CANONICAL_WORKS.find(w => w.code.toLowerCase() === lower);")
    lines.append("}")
    lines.append("")

    out_file.write_text("\n".join(lines), encoding="utf-8")
    print(f"Exported canonical works to {out_file}")


if __name__ == "__main__":
    export_ts()
